// Stock firmware has no kill switch, and on its own it does not quite fail closed. Measured
// 2026-09-24 with a device pinned to wgc1 (ARCHITECTURE.md "The fail-closed guard"):
//
//   - a tunnel whose server stops answering blocks the device, which is right;
//   - a watchdog rebuild let one reply out through the default connection, in the second the
//     firmware spent rebuilding the tunnel's routing table;
//   - a DISABLE let the device out for as long as the tunnel was off, through the default
//     connection, and in the clear when that is the plain internet.
//
// The firmware's own tunnel table can't close that gap: it rebuilds it on every restart, and fills
// it with a copy of main - the WAN default, and host routes via the WAN to the router's own DNS
// servers. So the guard keeps a table of its own per tunnel, holding the tunnel's default and the
// router's local routes and never a route out of the WAN, and two rules per pinned device: rule 90
// looks the device up in that table, and rule 91 blackholes whatever it can't route (ID-364).
// When a tunnel stops, the kernel removes its routes from every table, ours included, so the
// device is blocked with nothing having to run. Rules survive everything but a reboot and
// `restart_net_and_phy`, and the boot hook, which stock calls with `firewall-start` whenever its
// routing changes, runs the guard again after both. Merlin's kill switch has the same shape: a
// deny rule that stays put, after a lookup, kept true by events rather than a timer.
//
// Stock only. Merlin has a real kill switch, and device assignment is a stock feature here.

