// A guard replaced on the router says so in both logs (ID-675).
//
// guard.sh on stock and merlin-guard.sh on Merlin follow the app's version, so an app update replaces them. The
// watchdog scripts said so in both logs and the guard did not: stock's said it only when the guard was the one
// thing out of date, and Merlin's only on one path. The check is in each guard's install, so every path that
// replaces it says so, and nothing is said for a first install or for a copy that already matched.

import 'package:cfg_pia_wg/fail_closed_guard.dart';
import 'package:cfg_pia_wg/firmware.dart';
import 'package:cfg_pia_wg/merlin_guard.dart';
import 'package:cfg_pia_wg/router_script_integrity.dart';
import 'package:flutter_test/flutter_test.dart';

import '../watchdog_test_utils.dart';

const String _stockPath = '/jffs/cfg-pia-wg/guard.sh';
const String _merlinPath = '/jffs/cfg-pia-wg/merlin-guard.sh';
const String _old = '#!/bin/sh\n# an older build\nexit 0\n';
const String _version = 'v0.8.221 build 591';
const String _olderWatchdog =
    'wgc1|1|1|48994|# watchdog_wgc1.sh - auto-generated by cfg-pia-wg v0.8.183 build 553; *do* *not* edit.|exit 0';
const String _olderGuard = 'guard|0|1|16475|# guard.sh - auto-generated by cfg-pia-wg; *do* *not* edit.|exit 0';

typedef _Log = void Function(String m, {bool isError, bool isSuccess, bool isWarning});

void main() {
  final saved = appVersionLabel;
  setUp(() => appVersionLabel = _version);
  tearDown(() => appVersionLabel = saved);

  /// A router whose guard at [path] reads [onRouter]; the rest answers nothing.
  RecordingSSHClient router(String path, String onRouter, {String firmware = '', String health = ''}) =>
      RecordingSSHClient(responder: (cmd) {
        if (cmd == 'nvram get 3rd-party') return firmware;
        if (cmd == kScriptHealthCommand) return health;
        if (cmd.startsWith("cat '$path'")) return onRouter;
        return '';
      });

  Future<String> run(RecordingSSHClient c, String cmd) async => String.fromCharCodes(await c.run(cmd)).trim();

  FailClosedGuard stockGuard(RecordingSSHClient c, _Log onLog) =>
      FailClosedGuard(read: (x) => run(c, x), run: (x) => run(c, x), onLog: onLog);

  MerlinGuard merlinGuard(RecordingSSHClient c, _Log onLog) =>
      MerlinGuard(read: (x) => run(c, x), run: (x) => run(c, x), onLog: onLog);

  /// The app log lines and the router log commands that [body] produced.
  Future<({List<String> app, List<String> router})> logsOf(RecordingSSHClient c, Future<void> Function(_Log onLog) body) async {
    final app = <String>[];
    await body((m, {isError = false, isSuccess = false, isWarning = false}) => app.add(m));
    return (app: app, router: c.commands.where((x) => x.startsWith('logger')).toList());
  }

  void expectSaidOnce(({List<String> app, List<String> router}) l, String line) {
    expect(l.app.where((m) => m.contains(line)), hasLength(1), reason: 'the app log says it once');
    expect(l.router.where((x) => x.contains(line)), hasLength(1), reason: 'the router log says it once');
  }

  group('stock, guard.sh', () {
    test('a copy from another build is replaced, and both logs name the file and the version', () async {
      final c = router(_stockPath, _old);
      final l = await logsOf(c, (onLog) => stockGuard(c, onLog).install());
      expect(c.files.containsKey(_stockPath), isTrue, reason: 'the script was written');
      expectSaidOnce(l, 'guard.sh updated to $_version');
    });

    test('a first install is not a replacement, and says nothing of one', () async {
      final c = router(_stockPath, '');
      final l = await logsOf(c, (onLog) => stockGuard(c, onLog).install());
      expect(c.files.containsKey(_stockPath), isTrue, reason: 'it was installed');
      expect(l.app.where((m) => m.contains('updated to')), isEmpty);
      expect(l.router, isEmpty);
    });

    test('a copy that already matches writes nothing and says nothing', () async {
      final c = router(_stockPath, kGuardScript);
      final l = await logsOf(c, (onLog) => stockGuard(c, onLog).install());
      expect(c.files.containsKey(_stockPath), isFalse);
      expect(l.app, isEmpty);
      expect(l.router, isEmpty);
    });

    test('at the first connection, the guard alone out of date says so in both logs', () async {
      useStock();
      final c = router(_stockPath, _old, health: _olderGuard);
      final l = await logsOf(c, (onLog) async {
        final r = await checkRouterScripts(c, canUpdate: true, onLog: onLog);
        expect(r.updated, ['guard.sh']);
      });
      expectSaidOnce(l, 'guard.sh updated to $_version');
    });

    test('a guard carried along by a watchdog script update says so too', () async {
      useStock();
      final c = router(_stockPath, _old, health: _olderWatchdog);
      final l = await logsOf(c, (onLog) async {
        final r = await checkRouterScripts(c, canUpdate: true, onLog: onLog);
        expect(r.updated, ['watchdog_wgc1.sh']);
      });
      expectSaidOnce(l, 'guard.sh updated to $_version');
    });

    test('the guard ensure that DEVICES calls says so when it replaces the copy', () async {
      final c = router(_stockPath, _old);
      final l = await logsOf(c, (onLog) => stockGuard(c, onLog).ensure(quiet: true));
      expectSaidOnce(l, 'guard.sh updated to $_version');
    });

    test('a router log line that cannot be written does not undo the update', () async {
      final app = <String>[];
      await logGuardReplaced('guard.sh',
          run: (_) async => throw Exception('router gone'),
          onLog: (m, {isError = false, isSuccess = false, isWarning = false}) => app.add(m));
      expect(app, ['guard.sh updated to $_version.']);
    });
  });

  group('Merlin, merlin-guard.sh', () {
    test('a copy from another build is replaced, and both logs name the file and the version', () async {
      final c = router(_merlinPath, _old);
      final l = await logsOf(c, (onLog) => merlinGuard(c, onLog).install());
      expect(c.files.containsKey(_merlinPath), isTrue, reason: 'the script was written');
      expectSaidOnce(l, 'merlin-guard.sh updated to $_version');
    });

    test('a first install is not a replacement, and says nothing of one', () async {
      final c = router(_merlinPath, '');
      final l = await logsOf(c, (onLog) => merlinGuard(c, onLog).install());
      expect(c.files.containsKey(_merlinPath), isTrue, reason: 'it was installed');
      expect(l.app.where((m) => m.contains('updated to')), isEmpty);
      expect(l.router, isEmpty);
    });

    test('a copy that already matches writes nothing and says nothing', () async {
      final c = router(_merlinPath, kMerlinGuardScript);
      final l = await logsOf(c, (onLog) => merlinGuard(c, onLog).install());
      expect(c.files.containsKey(_merlinPath), isFalse);
      expect(l.app, isEmpty);
      expect(l.router, isEmpty);
    });

    test('at the first connection, with no watchdog script, the guard alone says so in both logs', () async {
      useMerlin();
      final c = router(_merlinPath, _old, firmware: 'merlin');
      final l = await logsOf(c, (onLog) async {
        final r = await checkRouterScripts(c, canUpdate: true, onLog: onLog);
        expect(r.updated, ['merlin-guard.sh']);
      });
      expectSaidOnce(l, 'merlin-guard.sh updated to $_version');
    });

    test('a guard carried along by a watchdog script update says so too, once', () async {
      useMerlin();
      final c = router(_merlinPath, _old, firmware: 'merlin', health: _olderWatchdog);
      final l = await logsOf(c, (onLog) async {
        final r = await checkRouterScripts(c, canUpdate: true, onLog: onLog);
        expect(r.updated, ['watchdog_wgc1.sh']);
      });
      expectSaidOnce(l, 'merlin-guard.sh updated to $_version');
    });

    test('the guard ensure that DEVICES calls says so when it replaces the copy', () async {
      final c = router(_merlinPath, _old);
      final l = await logsOf(c, (onLog) => merlinGuard(c, onLog).ensure(quiet: true));
      expectSaidOnce(l, 'merlin-guard.sh updated to $_version');
    });
  });
}
