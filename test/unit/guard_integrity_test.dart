// guard.sh checks itself and keeps its errors (ID-484, ID-485), run for real against the fake stock
// router in guard_harness.dart.
//
// A guard cut short would take fail-closed away from every pinned device, silently, as a cut-short
// watchdog did on 2026-10-29. Each test here is paired with a control that takes the protection out.

@Timeout(Duration(minutes: 2))
library;

import 'dart:convert';
import 'dart:io';

import 'package:cfg_pia_wg/fail_closed_guard.dart';
import 'package:cfg_pia_wg/firmware.dart';
import 'package:cfg_pia_wg/router_log_paging.dart';
import 'package:cfg_pia_wg/router_script_integrity.dart';
import 'package:flutter_test/flutter_test.dart';

import 'guard_harness.dart';

/// guard.sh cut short on a whole line inside its rule-adding loop, so the shell meets the end of the
/// file in the middle of a command.
String cutShort(String s) => s.substring(0, s.indexOf('\n', s.indexOf('for E in \$WANT; do')) + 1);

void main() {
  final g = GuardRouter();
  final skip = g.shell == null ? 'no POSIX shell on the PATH' : null;

  setUp(g.setUp);
  tearDown(g.tearDown);

  /// A watchdog script for [slot] that records how it was called.
  File fakeWatchdog(int slot) {
    final f = File('${g.dir.path}/watchdog_wgc$slot.sh')
      ..writeAsStringSync('#!/bin/sh\necho "wgc$slot \$1 \$2" >> "\$STATE/fault_calls"\n');
    if (!Platform.isWindows) Process.runSync('chmod', ['+x', f.path]);
    return f;
  }

  List<String> faultCalls() {
    final f = File('${g.state.path}/fault_calls');
    return f.existsSync() ? f.readAsLinesSync() : [];
  }

  group('guard.sh as written', () {
    test('ends with the line it checks for, and carries the app version (ID-487)', () {
      final saved = appVersionLabel;
      addTearDown(() => appVersionLabel = saved);
      appVersionLabel = 'v0.8.184 build 554';
      expect(kGuardScript.endsWith('exit 0\n${scriptEndLine('guard.sh')}\n'), isTrue);
      expect(kGuardScript, contains('"# end of guard.sh"'), reason: 'the self-check names the same line');
      expect(kGuardScript.split('\n')[1], '# guard.sh - auto-generated by cfg-pia-wg v0.8.184 build 554; *do* *not* edit.');
      appVersionLabel = '';
      expect(kGuardScript.split('\n')[1], '# guard.sh - auto-generated by cfg-pia-wg; *do* *not* edit.');
    });
  });

  test('its check is in the first 4,000 bytes, where TESTING GRD-10 and the live run cut it', () {
    // Measured 2026-11-01: the check ended at 2,345 bytes.
    expect(utf8.encode(kGuardScript.substring(0, kGuardScript.indexOf('# Every error this run writes'))).length, lessThan(4000));
  });

  group('a damaged guard.sh (ID-484)', () {
    test('logs a red ERROR, asks each guarded slot to email, and adds no rule', () async {
      g.set('vpnc_dev_policy_list', '1>192.0.2.50>>9>');
      fakeWatchdog(1);
      fakeWatchdog(5);
      g.script.writeAsStringSync(cutShort(kGuardScript));
      final r = await g.run();
      expect(r.exitCode, 1, reason: '${r.stdout}${r.stderr}');
      final line = g.log().firstWhere((l) => l.contains('is damaged'), orElse: () => '');
      expect(line, startsWith('ERROR: guard.sh is damaged ('));
      expect(line, contains('so the fail-closed guard is not running'));
      expect(isRouterLogError('Oct 29 15:10:00 cfg-pia-wg: $line'), isTrue);
      expect(faultCalls(), hasLength(1), reason: 'wgc1 guards the pinned device; wgc5 guards nothing');
      expect(faultCalls().single, startsWith('wgc1 fault guard.sh is damaged ('));
      expect(g.rules(), isEmpty);
    }, skip: skip);

    test('control: with the check taken out, the same cut-short guard says nothing', () async {
      g.set('vpnc_dev_policy_list', '1>192.0.2.50>>9>');
      fakeWatchdog(1);
      g.script.writeAsStringSync(cutShort(kGuardScript.replaceFirst(r'if [ "$(tail -n 1 "$0"', r'if false && [ "$(tail -n 1 "$0"')));
      await g.run();
      expect(g.log().any((l) => l.contains('is damaged')), isFalse);
      expect(faultCalls(), isEmpty);
    }, skip: skip);

    test('control: the whole guard runs as it always has', () async {
      g.set('vpnc_dev_policy_list', '1>192.0.2.50>>9>');
      final r = await g.run();
      expect(r.exitCode, 0, reason: '${r.stdout}${r.stderr}');
      expect(g.log().any((l) => l.contains('ERROR')), isFalse);
      expect(g.rules(), isNotEmpty);
    }, skip: skip);
  });

  group("the guard's errors are kept (ID-485)", () {
    test('what a run writes to stderr is kept for the watchdog to report', () async {
      g.script.writeAsStringSync(kGuardScript.replaceFirst('if [ "\$1" = "soon" ]; then', 'echo boom >&2\nif [ "\$1" = "soon" ]; then'));
      await g.run();
      final files = g.errorFiles();
      expect(files, hasLength(1));
      expect(files.single.readAsStringSync(), 'boom\n');
    }, skip: skip);

    test('a run with nothing to say leaves no file', () async {
      g.set('vpnc_dev_policy_list', '1>192.0.2.50>>9>');
      await g.run();
      await g.run(['clear']);
      expect(g.errorFiles(), isEmpty, reason: [for (final f in g.errorFiles()) f.readAsStringSync()].join('\n---\n'));
    }, skip: skip);

    test('control: without the redirect, the same error is lost', () async {
      g.script.writeAsStringSync(kGuardScript
          .replaceFirst('exec 2>>"\$GERR"', ':')
          .replaceFirst('if [ "\$1" = "soon" ]; then', 'echo boom >&2\nif [ "\$1" = "soon" ]; then'));
      await g.run();
      expect(g.errorFiles(), isEmpty);
    }, skip: skip);
  });
}
