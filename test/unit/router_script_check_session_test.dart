// The check of the scripts on the router, as the app runs it: on each new connection, before any
// action uses it (ID-483, ID-486, ID-487).

import 'dart:async';
import 'dart:typed_data';

import 'package:cfg_pia_wg/firmware.dart';
import 'package:cfg_pia_wg/router_script_integrity.dart';
import 'package:cfg_pia_wg/router_session.dart';
import 'package:cfg_pia_wg/router_watchdog.dart';
import 'package:cfg_pia_wg/session_controller.dart';
import 'package:cfg_pia_wg/widget_key.dart';
import 'package:cfg_pia_wg/widget_key_service.dart';
import 'package:cfg_pia_wg/widget_status_service.dart' show kWidgetReadScript, kWidgetReadScriptPath, kWidgetStatusCommand;
import 'package:flutter_test/flutter_test.dart';

import '../watchdog_test_utils.dart';
import '../widget_key_router_fake.dart';

const String kDamaged5 =
    'wgc5|1|1|7940|# watchdog_wgc5.sh - auto-generated by cfg-pia-wg v0.8.184 build 554; *do* *not* edit.|else';

void main() {
  final saved = appVersionLabel;
  setUp(() {
    appVersionLabel = 'v0.8.184 build 554';
    clearKeptRouterLog();
  });
  tearDown(() {
    appVersionLabel = saved;
    clearKeptRouterLog();
  });

  group('RouterSession.onConnected', () {
    test('runs once per new connection, with it, before the action', () async {
      final c = RecordingSSHClient();
      final seen = <String>[];
      final s = RouterSession(connect: () async => c, onConnected: (client) async {
        expect(identical(client, c), isTrue);
        seen.add('hook');
        await client.run('echo from-hook');
      });
      await s.run('echo action');
      await s.run('echo again');
      expect(seen, ['hook']);
      expect(c.commands, ['echo from-hook', 'echo action', 'echo again']);
    });

    test('a hook that fails or hangs does not stop the action', () async {
      final c = RecordingSSHClient();
      final logs = <String>[];
      final failing = RouterSession(connect: () async => c, onConnected: (_) async => throw Exception('no'));
      await failing.run('echo one');
      final hanging = RouterSession(
          connect: () async => c,
          onConnected: (_) => Completer<void>().future,
          connectedHookLimit: const Duration(milliseconds: 50),
          onLog: (m, {isError = false, isSuccess = false, isWarning = false}) => logs.add(m));
      await hanging.run('echo two');
      expect(c.commands, ['echo one', 'echo two']);
      expect(logs.single, contains('carrying on without it'));
    });
  });

  // ID-467: the widget's read script and this phone's key line, kept current on every connection,
  // paid or not, since the script only reads.
  test("unpaid: this phone's long widget key line moves to the short form, with its script", () async {
    useStock();
    final key = Uint8List.fromList(List.filled(32, 7));
    final r = FakeKeysRouter('ssh-ed25519 AAAAOTHER andrew@laptop\n'
        '${openSshPublicKeyLine(key, restriction: widgetKeyRestriction(kWidgetStatusCommand), comment: kWidgetKeyComment)}');
    final c = SessionController(checkRouterScripts: true, tickInterval: const Duration(hours: 1), ownWidgetKey: () async => key)
      ..routerIp = '192.168.50.1'
      ..sshUsername = 'admin'
      ..sshPassword = 'secret';
    c.setUnlocked(false);
    addTearDown(c.dispose);
    await c.routerSession(() async => r.client).run('echo action');
    expect(r.nv, 'ssh-ed25519 AAAAOTHER andrew@laptop\n${widgetKeyLine(key)}');
    expect(r.files[kWidgetReadScriptPath], kWidgetReadScript);
    expect(c.log.any((e) => e.isSuccess && e.message.contains('short form')), isTrue);
    expect(r.client.commands.last, 'echo action', reason: 'before the action, which still runs');
  });

  group('the app checks each router once a run (ID-487)', () {
    RecordingSSHClient router({String health = kDamaged5}) => RecordingSSHClient(responder: (cmd) {
          if (cmd == 'nvram get 3rd-party') return '';
          if (cmd == kScriptHealthCommand) return health;
          return '';
        });

    SessionController controller({required bool unlocked}) {
      final c = SessionController(checkRouterScripts: true, tickInterval: const Duration(hours: 1))
        ..routerIp = '192.168.50.1'
        ..sshUsername = 'admin'
        ..sshPassword = 'secret';
      c.setUnlocked(unlocked);
      addTearDown(c.dispose);
      return c;
    }

    test('paid: a damaged script is replaced and the screen is told', () async {
      useStock();
      final r = router();
      final c = controller(unlocked: true);
      final notices = <String>[];
      c.onNotice = notices.add;
      await c.routerSession(() async => r).run('echo action');
      expect(r.files.containsKey(watchdogScriptPath(5)), isTrue);
      expect(notices.single, 'The scripts on the router were updated to v0.8.184 build 554: watchdog_wgc5.sh.');
      expect(c.routerScriptProblems, isEmpty);
      expect(c.log.any((e) => e.isError && e.message.contains('watchdog_wgc5.sh on the router is damaged')), isTrue);
    });

    test('unpaid: nothing is written, and the banner has the problem', () async {
      useStock();
      final r = router();
      final c = controller(unlocked: false);
      var told = 0;
      c.addListener(() => told++);
      await c.routerSession(() async => r).run('echo action');
      expect(r.commands.any((x) => x.startsWith('cat ')), isFalse);
      expect(c.routerScriptProblems.single, startsWith('watchdog_wgc5.sh on the router is damaged'));
      expect(told, greaterThan(0), reason: 'the main menu redraws for the banner');
      c.clearRouterScriptProblems();
      expect(c.routerScriptProblems, isEmpty);
    });

    test('once per router a run of the app, not at every reconnect', () async {
      useStock();
      final r = router(health: '');
      final c = controller(unlocked: true);
      await c.routerSession(() async => r).run('echo one');
      await c.closeRouterSession();
      await c.routerSession(() async => r).run('echo two');
      expect(r.count(kScriptHealthCommand), 1);
    });

    test('off unless asked for, so a test router sees only its own commands', () async {
      final r = router();
      final c = SessionController(tickInterval: const Duration(hours: 1))..routerIp = '192.168.50.1';
      addTearDown(c.dispose);
      await c.routerSession(() async => r).run('echo action');
      expect(r.commands, ['echo action']);
    });
  });

  group('router log lines kept while the router could not be reached (ID-483)', () {
    test('are written at the next connection, with when they happened', () async {
      keepForRouterLog('ERROR during update of the watchdog scripts: connection lost', at: DateTime(2026, 10, 29, 15, 8, 30));
      expect(keptRouterLogCount, 1);
      final r = RecordingSSHClient();
      final c = SessionController(tickInterval: const Duration(hours: 1))..routerIp = '192.168.50.1';
      addTearDown(c.dispose);
      await c.routerSession(() async => r).run('echo action');
      final line = r.commands.firstWhere((x) => x.startsWith('logger'), orElse: () => '');
      expect(line, contains('ERROR during update of the watchdog scripts: connection lost'));
      expect(line, contains('at 2026-10-29 15:08:30'));
      expect(keptRouterLogCount, 0);
      expect(r.commands.indexOf(line), lessThan(r.commands.indexOf('echo action')));
    });

    test('a failed update keeps its line when the router cannot take it', () async {
      final r = RecordingSSHClient(throwOn: ['3rd-party', 'logger']);
      await expectLater(RouterWatchdog(r).redeployScripts(), throwsException);
      expect(keptRouterLogCount, 1);
    });
  });
}
